// What a write's answer carries besides its body (the draft version it left), set by a
// handler the write passes on its way to the echo below.
export const ANSWER_HEADERS = new WeakMap<object, Record<string, string>>();
export type Mounted = { frame: ReturnType<Page['frameLocator']>; puts: Array<Record<string, unknown>> };
export async function mountCanvas(page: Page, opts: { html?: string; settings?: Record<string, unknown>; beforeGoto?: (p: Page) => Promise<unknown> } = {}): Promise<Mounted> {
  const settings = opts.settings ?? SETTINGS;
  await installApp(page, { api: { ...API, '/settings': { data: settings } } });
  const puts: Array<Record<string, unknown>> = [];
  // later-registered routes win: capture PUT /settings (echo the body back, the
  // real handler shape) and serve the stamped preview HTML.
  await page.route('**/functions/v1/presence/settings**', (route: Route) => {
    if (route.request().method() === 'PUT') {
      const body = route.request().postDataJSON() as Record<string, unknown>;
      puts.push(body);
      return route.fulfill({ status: 200, contentType: 'application/json', headers: ANSWER_HEADERS.get(route.request()), body: JSON.stringify({ data: { ...settings, ...body, section_meta: META } }) });
    }
    return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ data: settings }) });
  });
  await page.route('**/functions/v1/presence/preview**', (route: Route) =>
    route.fulfill({ status: 200, contentType: 'text/html; charset=utf-8', body: opts.html ?? PAGE_HTML(SECTIONS) }));
  if (opts.beforeGoto) await opts.beforeGoto(page);
  // the editor's tip comes up 0.4 s after opening, and on a phone it can sit over the section a
  // test has just hovered: seen, it stays away (list item 108)
  await page.addInitScript(() => { try { const s = JSON.parse(localStorage.getItem('dds-hints') || '{}'); localStorage.setItem('dds-hints', JSON.stringify({ ...s, 'edit-tap': 1, 'edit-doubleclick': 1 })); } catch { /* storage may be denied */ } });
  await page.goto('/presence.html#design');
  // visual refresh: the builder sits under the site's top row with the sub-view
  // tab strip marking Design — the canvas itself is unchanged
  await expect(page.locator('html')).toHaveClass(/dc-edit/);   // the Design view is the full-screen Edit mode
  await expect(page.locator('#btnPublish')).toHaveText('Publish');
  const frame = page.frameLocator('#designPreview');
  await expect(frame.locator('#main > section').first()).toBeVisible();
  await expect(frame.locator('#dds-dc-bar')).toBeAttached();   // sections paint before the frame's load event, which is what wires double-click and hover
  return { frame, puts };
}
